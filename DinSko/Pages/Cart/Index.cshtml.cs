using DinSko.Models;
using DinSko.Services;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.RazorPages;
using System.Security.Claims;

namespace DinSko.Pages.Cart
{
    [Authorize]
    public class IndexModel : PageModel
    {
        private readonly CartService _cartService;
        private readonly ProductService _productService;
        private readonly ProductVariantService _productVariantService;

        public IndexModel(
            CartService cartService,
            ProductService productService,
            ProductVariantService productVariantService)
        {
            _cartService = cartService;
            _productService = productService;
            _productVariantService = productVariantService;
        }

        public List<CartItemViewModel> Items { get; set; } =
            new List<CartItemViewModel>();

        public string Message { get; set; }

        public class CartItemViewModel
        {
            public int CartItemId { get; set; }
            public int ProductVariantId { get; set; }
            public string ProductName { get; set; }
            public int Size { get; set; }
            public int Quantity { get; set; }
            public decimal Price { get; set; }
            public int Stock { get; set; }
        }

        // Get the current user's cart using the authenticated user ID
        private DinSko.Models.Cart GetCurrentCart()
        {
            string userIdValue =
                User.FindFirstValue(ClaimTypes.NameIdentifier);

            if (!int.TryParse(userIdValue, out int userId))
            {
                return null;
            }

            return _cartService.GetByUserId(userId);
        }

        public IActionResult OnGet()
        {
            // Display a message after an operation
            Message = TempData["CartMessage"] as string;

            DinSko.Models.Cart cart = GetCurrentCart();

            if (cart == null)
            {
                return Page();
            }

            IEnumerable<CartItem> cartItems =
                _cartService.GetItems(cart.CartId);

            foreach (CartItem item in cartItems)
            {
                ProductVariant variant =
                    _productVariantService.GetById(item.ProductVariantId);

                if (variant == null)
                {
                    continue;
                }

                Product product =
                    _productService.GetById(variant.ProductId);

                if (product == null)
                {
                    continue;
                }

                Items.Add(new CartItemViewModel
                {
                    CartItemId = item.CartItemId,
                    ProductVariantId = variant.ProductVariantId,
                    ProductName = product.Name,
                    Size = variant.Size,
                    Quantity = item.Quantity,
                    Price = product.Price,
                    Stock = variant.Stock
                });
            }

            return Page();
        }

        public IActionResult OnPostAdd(int productVariantId, int quantity)
        {
            // Get the authenticated user's ID
            string userIdValue =
                User.FindFirstValue(ClaimTypes.NameIdentifier);

            if (!int.TryParse(userIdValue, out int userId))
            {
                return Challenge();
            }

            // Validate the requested quantity
            if (quantity < 1 || quantity > 10)
            {
                TempData["CartMessage"] =
                    "Choose a quantity between 1 and 10.";

                return RedirectToPage("/Index");
            }

            // Verify that the selected product variant exists
            ProductVariant variant =
                _productVariantService.GetById(productVariantId);

            if (variant == null)
            {
                TempData["CartMessage"] =
                    "The selected product size is not available.";

                return RedirectToPage("/Index");
            }

            // Get or create the current user's cart
            DinSko.Models.Cart cart =
                _cartService.GetByUserId(userId);

            if (cart == null)
            {
                cart = new DinSko.Models.Cart
                {
                    UserId = userId
                };

                _cartService.Create(cart);

                // Retrieve the cart ID generated by the database
                cart = _cartService.GetByUserId(userId);
            }

            if (cart == null)
            {
                TempData["CartMessage"] =
                    "Could not create your cart.";

                return RedirectToPage("/Index");
            }

            // Add the item only if enough stock is available
            bool added = _cartService.AddItemIfInStock(new CartItem
            {
                CartId = cart.CartId,
                ProductVariantId = variant.ProductVariantId,
                Quantity = quantity
            });

            // Display the result on the home page
            TempData["CartMessage"] = added
                ? "Product added to cart."
                : "Not enough stock available.";

            return RedirectToPage("/Index");
        }

        public IActionResult OnPostUpdate(int itemId, int quantity)
        {
            DinSko.Models.Cart cart = GetCurrentCart();

            if (cart == null)
            {
                return Challenge();
            }

            // Validate the requested quantity
            if (quantity < 1 || quantity > 10)
            {
                TempData["CartMessage"] =
                    "Choose a quantity between 1 and 10.";

                return RedirectToPage();
            }

            // Verify cart ownership and available stock
            bool updated = _cartService.UpdateItemQuantity(
                cart.CartId, itemId, quantity);

            TempData["CartMessage"] = updated
                ? "Cart quantity updated."
                : "Quantity could not be updated. Check the available stock.";

            return RedirectToPage();
        }

        public IActionResult OnPostRemove(int itemId)
        {
            DinSko.Models.Cart cart = GetCurrentCart();

            if (cart == null)
            {
                return Challenge();
            }

            // Remove only an item belonging to the current user's cart
            bool removed = _cartService.RemoveItemFromCart(
                cart.CartId, itemId);

            TempData["CartMessage"] = removed
                ? "Product removed from cart."
                : "The product could not be removed.";

            return RedirectToPage();
        }
    }
}